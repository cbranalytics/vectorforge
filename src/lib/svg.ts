import type { Layer, PathLayer, SvgSettings, TextLayer, TraceResult } from '../types.ts'

export interface BuildSvgOptions extends SvgSettings {
  sourceName?: string
  onlyVisible?: boolean
  scale?: number
  layerOpacity?: (layer: Layer) => number
}

function roundNumbers(input: string, precision: number): string {
  return input.replace(/-?\d*\.?\d+/g, (m) => {
    const n = Number(m)
    if (!Number.isFinite(n)) return m
    return String(Number(n.toFixed(precision)))
  })
}

export function escapeXml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;')
}

function serializePathLayer(layer: PathLayer, opts: BuildSvgOptions, indent: string, opacity: number): string {
  const precision = opts.precision
  const primitiveLayers = layer.paths.filter((p) => p.kind !== 'path')
  const pathParts = layer.paths.filter((p) => p.kind === 'path' && p.d)
  const lines: string[] = []
  const rule = layer.fillRule === 'evenodd' ? ' fill-rule="evenodd"' : ''
  const op = opacity < 1 ? ` opacity="${Number(opacity.toFixed(3))}"` : ''
  if (pathParts.length > 0) {
    const d = roundNumbers(pathParts.map((p) => p.d).join(''), precision)
    lines.push(`${indent}<path d="${d}" fill="${layer.color}"${rule} />`)
  }
  for (const shape of primitiveLayers) {
    if (shape.kind === 'rect' && shape.rect) {
      const r = shape.rect
      lines.push(
        `${indent}<rect x="${Number(r.x.toFixed(precision))}" y="${Number(r.y.toFixed(precision))}" width="${Number(r.w.toFixed(precision))}" height="${Number(r.h.toFixed(precision))}" fill="${layer.color}"${rule} />`,
      )
    } else if (shape.kind === 'circle' && shape.circle) {
      const c = shape.circle
      lines.push(
        `${indent}<circle cx="${Number(c.cx.toFixed(precision))}" cy="${Number(c.cy.toFixed(precision))}" r="${Number(c.r.toFixed(precision))}" fill="${layer.color}"${rule} />`,
      )
    }
  }
  if (lines.length === 0) return ''
  if (opts.pretty) {
    return `${indent}<g id="${layer.id}" data-nodes="${layer.nodes}"${op}>\n${lines.join('\n')}\n${indent}</g>`
  }
  return `${indent}<g id="${layer.id}"${op}>${lines.join('').trim()}</g>`
}

function serializeTextLayer(layer: TextLayer, opts: BuildSvgOptions, indent: string, opacity: number): string {
  const p = opts.precision
  const rotation = layer.rotation ? ` transform="rotate(${Number(layer.rotation.toFixed(2))} ${Number(layer.x.toFixed(p))} ${Number(layer.y.toFixed(p))})"` : ''
  const italic = layer.italic ? ' font-style="italic"' : ''
  const op = opacity < 1 ? ` opacity="${Number(opacity.toFixed(3))}"` : ''
  const fit = !rotation && layer.w > 0 ? ` textLength="${Number(layer.w.toFixed(p))}" lengthAdjust="spacingAndGlyphs"` : ''
  const attrs = [
    `x="${Number(layer.x.toFixed(p))}"`,
    `y="${Number(layer.y.toFixed(p))}"`,
    `font-family="${escapeXml(layer.fontFamily)}"`,
    `font-size="${Number(layer.fontSize.toFixed(p))}"`,
    `font-weight="${layer.fontWeight}"${italic}`,
    `fill="${layer.color}"`,
    `xml:space="preserve"`,
  ].join(' ')
  return `${indent}<text id="${layer.id}" ${attrs}${fit}${rotation}${op}>${escapeXml(layer.text)}</text>`
}

export function buildSvg(result: TraceResult, opts: BuildSvgOptions): string {
  const scale = opts.scale ?? result.scale ?? 1
  const indent = opts.pretty ? '  ' : ''
  const parts: string[] = []

  const header = [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${result.outWidth} ${result.outHeight}"`,
    ` width="${result.outWidth}" height="${result.outHeight}"`,
    ` shape-rendering="geometricPrecision" fill="none">`,
  ].join('')

  if (opts.metadata) {
    const name = opts.sourceName ? ` from ${escapeXml(opts.sourceName)}` : ''
    parts.push(`<title>VectorForge AI vector${name}</title>`)
    parts.push(
      `<desc>Generated by VectorForge AI - ${result.stats.colors} shape layers, ${result.stats.nodes} nodes, ${result.stats.textBlocks} live text blocks.</desc>`,
    )
  }

  const body: string[] = []
  const scaleAttr = Math.abs(scale - 1) > 1e-6 ? ` transform="scale(${Number(scale.toFixed(6))})"` : ''

  if (opts.includeBackground && result.background) {
    body.push(`${indent}<rect x="0" y="0" width="${result.outWidth}" height="${result.outHeight}" fill="${result.background}" />`)
  }

  if (scaleAttr !== '') {
    const inner: string[] = []
    for (const layer of result.layers) {
      if (opts.onlyVisible && !layer.visible) continue
      const opacity = opts.layerOpacity?.(layer) ?? 1
      if (layer.kind === 'path') {
        const s = serializePathLayer(layer, opts, indent + indent, opacity)
        if (s) inner.push(s)
      } else {
        inner.push(serializeTextLayer(layer, opts, indent + indent, opacity))
      }
    }
    body.push(`${indent}<g${scaleAttr}>`, ...inner, `${indent}</g>`)
  } else {
    for (const layer of result.layers) {
      if (opts.onlyVisible && !layer.visible) continue
      const opacity = opts.layerOpacity?.(layer) ?? 1
      if (layer.kind === 'path') {
        const s = serializePathLayer(layer, opts, indent, opacity)
        if (s) body.push(s)
      } else {
        body.push(serializeTextLayer(layer, opts, indent, opacity))
      }
    }
  }

  const separator = opts.pretty ? '\n' : ''
  const content = opts.pretty ? body.join('\n') : body.join('')
  return `${header}${separator}${content}${opts.pretty ? '\n' : ''}</svg>`
}

export function renderPreviewUrl(svg: string): string {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`
}
